// Bochs VBE display driver. QEMU's stdvga emulates Bochs VBE 2.0 through the
// VBE dispi interface (ports 0x1CE/0x1CF): the kernel programs a linear
// framebuffer mode, maps it into the address space, and renders text with an
// embedded 8x16 PC font. This keeps the console fully independent of GOP.

const std = @import("std");
const vmm = @import("../mm/virtual.zig");
const pmem = @import("../mm/physical.zig");


pub const WIDTH: usize = 160; // cells across (1280 px / 8)
pub const HEIGHT: usize = 50; // cells down (800 px / 16)

pub const FB_PHYS: usize = 0xF8000000; // QEMU stdvga BAR0 linear FB base
pub const FB_WIDTH: usize = 1280;
pub const FB_HEIGHT: usize = 800;
pub const FB_BPP: usize = 32;

// Bochs VBE dispi registers (data port 0x1CF after index port 0x1CE).
const VBE_DISPI_INDEX_ID: u16 = 0;
const VBE_DISPI_INDEX_XRES: u16 = 1;
const VBE_DISPI_INDEX_YRES: u16 = 2;
const VBE_DISPI_INDEX_BPP: u16 = 3;
const VBE_DISPI_INDEX_ENABLE: u16 = 4;
const VBE_DISPI_INDEX_BANK: u16 = 5;
const VBE_DISPI_INDEX_VIRT_WIDTH: u16 = 6;
const VBE_DISPI_INDEX_VIRT_HEIGHT: u16 = 7;
const VBE_DISPI_INDEX_X_OFFSET: u16 = 8;
const VBE_DISPI_INDEX_Y_OFFSET: u16 = 9;

const VBE_DISPI_ENABLED: u16 = 0x01;
const VBE_DISPI_LFB_ENABLED: u16 = 0x40;
const VBE_DISPI_NOCLEARMEM: u16 = 0x80;

var fb: [*]volatile u32 = undefined;
var enabled: bool = false;
var font_virt: usize = 0; // virtual address of the copied 8x16 PC font
var font_phys: usize = 0; // physical (identity-accessible) base of the font

/// Low-level dispi write.
fn dispi(index: u16, value: u16) void {
    _ = index;
    asm volatile ("outw %[v], %[p]" : : [v] "{ax}" (value), [p] "{dx}" (@as(u16, 0x1CE)));
    asm volatile ("outw %[v], %[p]" : : [v] "{ax}" (value), [p] "{dx}" (@as(u16, 0x1CF)));
}

/// Read a dispi register.
fn dispi_read(index: u16) u16 {
    var v: u16 = undefined;
    asm volatile ("outw %[idx], %[p]" : : [idx] "{ax}" (index), [p] "{dx}" (@as(u16, 0x1CE)));
    asm volatile ("inw %[p], %[v]" : [v] "={ax}" (v) : [p] "{dx}" (@as(u16, 0x1CF)));
    return v;
}

/// Initialise the Bochs VBE interface and enable linear framebuffer mode
/// 1024x768x32. Falls back gracefully if the interface is not present.
pub fn init() void {
    _ = vmm;
    _ = pmem;
    // Confirm a Bochs VBE interface is reachable (ID register reads back
    // 0xB0C0 for Bochs VBE 2.0).
    dispi(VBE_DISPI_INDEX_ID, 0xB0C0);
    const vbe_id = dispi_read(VBE_DISPI_INDEX_ID);
    // For VBE 2.5 (0xB0C5) the mode is only accepted after writing the
    // full version code to the ID register once.
    dispi(VBE_DISPI_INDEX_ID, vbe_id);
    // Bochs VBE versions identify as 0xB0C4 (VBE 2.0) or 0xB0C5 (VBE 2.5);
    // anything else means the dispi interface is not present.
    if ((vbe_id & 0xFFF0) != 0xB0C0) {
        // No Bochs VBE: the console will not be able to render.
        return;
    }

    dispi(VBE_DISPI_INDEX_BPP, FB_BPP);
    dispi(VBE_DISPI_INDEX_XRES, FB_WIDTH);
    dispi(VBE_DISPI_INDEX_YRES, FB_HEIGHT);
    dispi(VBE_DISPI_INDEX_VIRT_WIDTH, FB_WIDTH);
    dispi(VBE_DISPI_INDEX_VIRT_HEIGHT, FB_HEIGHT);
    dispi(VBE_DISPI_INDEX_BANK, 0);
    dispi(VBE_DISPI_INDEX_ENABLE, VBE_DISPI_ENABLED | VBE_DISPI_LFB_ENABLED | VBE_DISPI_NOCLEARMEM);

    _ = dispi_read(VBE_DISPI_INDEX_XRES);
    _ = dispi_read(VBE_DISPI_INDEX_YRES);
    _ = dispi_read(VBE_DISPI_INDEX_BPP);

    // Locate the linear framebuffer. BAR0 of the video device tells us the
    // real LFB base; if the PCI probe fails we fall back to 0xF8000000.
    var lfb_phys: usize = FB_PHYS;
    const bar0 = pci_bar0();
    if (bar0 != 0) {
        lfb_phys = bar0 & ~@as(usize, 0xF);
    }
    fb = @as([*]volatile u32, @ptrFromInt(lfb_phys));

    // Copy the embedded 8x16 PC font into a kernel page so it is reachable
    // without linker shenanigans (the const array lives in read-only
    // kernel space, but a local copy keeps the driver self-contained).
    const font_page = pmem.alloc_frame();
    if (font_page == 0) return;
    const font_v = 0xFFFF8000F0000000;
    const mp = vmm.map_page(vmm.kernel_pml4_phys, font_v, font_page, vmm.PAGE_PRESENT | vmm.PAGE_WRITE);
    if (!mp) {
        pmem.free_frame(font_page);
        return;
    }
    const dest = @as([*]u8, @ptrFromInt(font_v))[0..(256 * 16)];
    var fi: usize = 0;
    while (fi < PC_FONT.len) : (fi += 1) {
        dest[fi] = PC_FONT[fi];
    }
    font_virt = font_v;
    font_phys = font_page;
    enabled = true;
}

pub fn is_enabled() bool {
    return enabled;
}

/// Read BAR0 of the PCI video device (bus 0, device 1, function 0 on q35)
/// and return its base address, or 0 if the probe fails.
fn pci_bar0() usize {
    // PCI configuration address port builds the address for dev 1 func 0
    // register 0x10 (BAR0): enable bit 31 | bus 0 | dev 1 (bit 11) | reg 0x10.
    asm volatile ("outl %[a], %[p]" : : [a] "r" (@as(u32, 0x80000810)), [p] "{dx}" (@as(u16, 0xCF8)));
    var bar: u32 = 0;
    asm volatile ("inl %[p], %[v]" : [v] "={ax}" (bar) : [p] "{dx}" (@as(u16, 0xCFC)));
    if ((bar & 1) != 0) return 0; // memory-mapped BARs have bit 0 clear
    return @as(usize, bar);
}

/// Render a glyph (8x16, from the embedded PC font) into the framebuffer.
pub fn draw_glyph(col: usize, row: usize, ch: u8, attr: u8) void {
    _ = vmm;
    if (!enabled or col >= WIDTH or row >= HEIGHT) return;
    const fg = PALETTE[attr & 0xF];
    const bg = PALETTE[(attr >> 4) & 0xF];
    // Compute the glyph pointer from the font's physical base (identity
    // mapped). Using the higher-half address would overflow on the ch*16
    // multiply and trip the safe-mode overflow check.
    const glyph_ptr = font_phys + @as(usize, ch) * 16;
    if (glyph_ptr == 0) return;
    const glyph = @as([*]const u8, @ptrFromInt(glyph_ptr));
    const x0 = col * 8;
    const y0 = row * 16;
    const stride = FB_WIDTH;
    var y: usize = 0;
    while (y < 16) : (y += 1) {
        const bits = glyph[y];
        var x: usize = 0;
        while (x < 8) : (x += 1) {
            const mask: u8 = @as(u8, 0x80) >> @truncate(x);
            const colour = if (bits & mask != 0) fg else bg;
            fb[(y0 + y) * stride + (x0 + x)] = colour;
        }
    }
}

pub fn put_char(col: usize, row: usize, ch: u8, attr: u8) void {
    if (ch == '\n') return;
    draw_glyph(col, row, ch, attr);
}

pub fn put_string(col: usize, row: usize, text: []const u8, attr: u8) void {
    if (row >= HEIGHT or !enabled) return;
    var c: usize = col;
    for (text) |ch| {
        if (ch == '\n' or c >= WIDTH) break;
        draw_glyph(c, row, ch, attr);
        c += 1;
    }
}

/// Scroll the display up one logical row and clear the bottom row.
pub fn scroll(attr: u8) void {
    if (!enabled) return;
    const row_pixels = 16;
    const row_bytes = FB_WIDTH * row_pixels;
    const total = FB_WIDTH * FB_HEIGHT;
    var i: usize = 0;
    while (i < total - row_bytes) : (i += 1) {
        fb[i] = fb[i + row_bytes];
    }
    const bg = PALETTE[(attr >> 4) & 0xF];
    i = total - row_bytes;
    while (i < total) : (i += 1) {
        fb[i] = bg;
    }
}

/// Erase a whole cell with the background colour from attr.
pub fn erase_cell(col: usize, row: usize, attr: u8) void {
    draw_glyph(col, row, ' ', attr);
}

/// Draw a block cursor in the cell at (col, row).
pub fn draw_cursor(col: usize, row: usize, attr: u8) void {
    draw_glyph(col, row, 0xdb, attr | 0x80);
}

pub fn clear() void {
    if (!enabled) return;
    for (fb[0 .. FB_WIDTH * FB_HEIGHT]) |*px| {
        px.* = 0;
    }
}

// The 16-colour VGA palette mapped to 24-bit RGB (u32 little-endian ABGR).
const PALETTE = [_]u32{
    0xFF000000, 0xFF0000AA, 0xFF00AA00, 0xFF00AAAA,
    0xFFAA0000, 0xFFAA00AA, 0xFFAA5500, 0xFFAAAAAA,
    0xFF555555, 0xFF5555FF, 0xFF55FF55, 0xFF55FFFF,
    0xFFFF5555, 0xFFFF55FF, 0xFFFFFF55, 0xFFFFFFFF,
};

/// C-callable module entry point for the kernel module registry.
pub fn init_module(sender: u32) callconv(.{ .x86_64_sysv = .{} }) bool {
    _ = sender;
    init();
    return enabled;
}

